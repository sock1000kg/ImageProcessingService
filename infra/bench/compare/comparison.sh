#!/usr/bin/env bash
# Regenerate the raw throughput tables in infra/bench/results/comparison.md.
#
#   bash infra/bench/compare/comparison.sh [--no-cpu]
#
# 1. summarize.py tables (--table-only, the runs' own summary.md is not touched) for the laptop runs (per model and size, with the base-model control run and deface).
# 2. Model-only CPU time per image (cpu_speed.py): the shipped engine model(s) and deface. Needs engine/training/.venv
#    (ultralytics) and the deface venv made by compare/deface.sh; --no-cpu skips it and keeps the previous rows.
# Only the block between the "generated" markers is replaced; the final comparison below it is written by hand.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=results/comparison.md
YOLO_PY=../../engine/training/.venv/bin/python
DEFACE_PY=.cache/deface-venv/bin/python
# the engine's models (committed): picked lightweight / standard, and the base model
M=../../engine/models
WEIGHTS=($M/yolo26n-1280-e20-crowd.pt@1280 $M/yolo26n-1280-e20-crowd.pt@960 $M/yolo26s-1280-e5-plates-frozen-x3.pt@1280
  $M/yolov8n-oiv7.pt@1280 $M/yolov8n-oiv7.pt@640)

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# summarize <title> <out> <run folders...> [--deface ...]: one generated table
summarize() {
  local title=$1
  shift
  python3 summarize.py "$@" --table-only --out "$tmp/t.md" > /dev/null
  echo
  echo "### Raw: $title"
  sed -e 's/^## /#### /' "$tmp/t.md"
}

cpu_rows() {
  if [ "${1:-}" = --no-cpu ] && [ -f "$OUT" ]; then
    sed -n '/^| Model | Input | Threads/,/^$/p' "$OUT" | sed '1,2d' | grep '^|'
    return
  fi
  $YOLO_PY compare/cpu_speed.py yolo --weights "${WEIGHTS[@]}" 2> /dev/null
  $DEFACE_PY compare/cpu_speed.py deface 2> /dev/null | grep '^|'
}

{
  echo "<!-- generated:start (bash infra/bench/compare/comparison.sh) -->"
  echo "## Raw comparison"
  echo
  echo "Generated by \`compare/comparison.sh\` on $(date +%F): \`summarize.py\` tables from the committed runs, then"
  echo "\`compare/cpu_speed.py\`. Rows are \`<model>/<run>\`; rows without a model are the old base model \`yolov8n-oiv7\` (control runs)."
  L=results/laptop-rtx3050-max
  N=yolo26n-1280-e20-crowd
  X=yolo26s-1280-e5-plates-frozen-x3
  for px in 640 960; do
    summarize "laptop (RTX 3050), web at 2 CPU, 3,726 images, $px px" $L/$N/${px}px $L/$X/${px}px
  done
  summarize "laptop (RTX 3050), web at 2 CPU, 3,726 images, 1280 px, with the base model and deface" \
    $L/$N/1280px $L/$X/1280px $L/yolov8n-oiv7/1280px --deface $L/deface/full $L/deface/640x480
  H=results/home-server-100
  for px in 960 1280; do
    summarize "lab (home-server, CPU), web at 0.5 CPU, 100 images, $px px" $H/$N/${px}px $H/$X/${px}px
  done
  summarize "lab (home-server, CPU), web at 0.5 CPU, 100 images, 640 px, base model (control)" $H/yolov8n-oiv7/640px
  echo
  echo "### Raw: model-only CPU time per image"
  echo
  echo "\`cpu_speed.py\`: inference only (no decode/upload/blur) on benchmark images, laptop i5-12500H limited to the"
  echo "given threads (the lab node has 2 cores)."
  echo
  echo "| Model | Input | Threads | Images | ms / image |"
  echo "| --- | --- | --- | --- | --- |"
  cpu_rows "${1:-}"
  echo "<!-- generated:end -->"
} > "$tmp/block.md"

if [ ! -f "$OUT" ]; then
  printf '# Throughput and speed\n\n<!-- generated:start -->\n<!-- generated:end -->\n\n## Final comparison\n' > "$OUT"
fi
python3 - "$OUT" "$tmp/block.md" <<'EOF'
import sys
path, block = sys.argv[1], open(sys.argv[2]).read().rstrip("\n")
text = open(path).read()
start, end = text.index("<!-- generated:start"), text.index("<!-- generated:end -->") + len("<!-- generated:end -->")
open(path, "w").write(text[:start] + block + text[end:])
EOF
echo "$OUT: raw comparison regenerated"
